<#
  devbox-team-sync (ADR 0007): hub environment_members -> Unix groups on the devbox.
  Source of truth: one hub environment per devbox repo (provider byo, metadata {devbox, repo}); its members
  are the people allowed into /work/<repo>. This script runs on the OWNER's PC (the hub key never leaves it,
  DPAPI), builds the desired state (no secrets: user ids -> linux names, roles, the hub SSH CA public key)
  and pipes it over ssh to `sudo devbox-teams apply` on the devbox, which converges users/groups/dirs.

    devbox-team-sync.ps1                      # sync (scheduled task devbox-team-sync, every 15 min)
    devbox-team-sync.ps1 -Plan                # print the desired state + devbox plan, change nothing
    devbox-team-sync.ps1 -Ensure codai,axiom  # create the hub project+environment for these repos if missing
    devbox-team-sync.ps1 -DesiredOnly         # print the desired-state JSON (tests / debugging)

  -Hub <url> / -KeyFile: defaults https://ai.codai.ro/v1 and ~/.codai/copilot.key (DPAPI hex).
  -FromFile <json>: use a recorded hub snapshot instead of HTTP (tests): {"environments":[...],"members":{envId:[...]},"ca":[...]}.
#>
param(
  [string]$Devbox = $(if ($env:DEVBOX_ADMIN_HOST) { $env:DEVBOX_ADMIN_HOST } else { 'ws-devbox' }),
  [string]$DevboxName = 'ws-devbox',
  [string]$Owner = 'dev',
  [string]$Hub = 'https://ai.codai.ro/v1',
  [string]$KeyFile = (Join-Path $HOME '.codai/copilot.key'),
  [string]$FromFile,
  [string[]]$Ensure = @(),
  [string]$Log = (Join-Path $HOME '.codai/logs/devbox-team-sync.log'),
  [switch]$Plan, [switch]$DesiredOnly
)
$ErrorActionPreference = 'Stop'
$Ensure = @($Ensure | ForEach-Object { $_ -split ',' } | ForEach-Object { $_.Trim().ToLowerInvariant() } | Where-Object { $_ })

function Get-HubKey {
  if ($env:CODAI_HUB_KEY) { return $env:CODAI_HUB_KEY }
  $txt = [IO.File]::ReadAllText($KeyFile).Trim()
  if ($txt -like 'codai*') { return $txt }
  Add-Type -AssemblyName System.Security
  $raw = [byte[]]::new($txt.Length / 2); for ($i = 0; $i -lt $raw.Length; $i++) { $raw[$i] = [Convert]::ToByte($txt.Substring($i * 2, 2), 16) }
  [Text.Encoding]::Unicode.GetString([Security.Cryptography.ProtectedData]::Unprotect($raw, $null, 'CurrentUser')).Trim()
}
$script:Key = $null
function Hub([string]$method, [string]$path, $body) {
  if (-not $script:Key) { $script:Key = Get-HubKey }
  $p = @{ Method = $method; Uri = "$Hub$path"; Headers = @{ Authorization = "Bearer $script:Key" }; TimeoutSec = 30 }
  if ($null -ne $body) { $p.Body = ($body | ConvertTo-Json -Depth 6 -Compress); $p.ContentType = 'application/json' }
  Invoke-RestMethod @p
}

# A devbox environment: byo, not destroyed, name 'devbox:<devboxName>:<repo>' (metadata is not settable via
# the public API, so the name carries the mapping; slug devbox-<repo>-<4> is generated by the hub).
function Get-RepoOfEnv($e) { if ("$($e.name)" -match "^devbox:$([regex]::Escape($DevboxName)):([A-Za-z0-9._-]+)$") { $Matches[1] } else { $null } }

function Get-Snapshot {
  if ($FromFile) { return (Get-Content -LiteralPath $FromFile -Raw | ConvertFrom-Json -AsHashtable) }
  $envs = @((Hub GET '/environments').environments | Where-Object { $_.state -ne 'destroyed' -and (Get-RepoOfEnv $_) })
  if ($Ensure) {
    $have = @($envs | ForEach-Object { (Get-RepoOfEnv $_).ToLowerInvariant() })
    $projects = @((Hub GET '/projects').projects)
    foreach ($r in $Ensure | Where-Object { $_ -notin $have }) {
      $slug = "devbox-$r"
      $pj = $projects | Where-Object slug -eq $slug | Select-Object -First 1
      if (-not $pj) { $pj = (Hub POST '/projects' @{ name = "devbox $r"; slug = $slug; isolation = 'shared_vm' }).project; "hub project $slug created" | Write-Host }
      $e = (Hub POST '/environments' @{ project_id = $pj.id; name = "devbox:${DevboxName}:$r"; provider = 'byo'; idle_timeout_minutes = 30 }).environment
      "hub environment devbox:${DevboxName}:$r created ($($e.id))" | Write-Host
      $envs += $e
    }
  }
  $members = @{}
  foreach ($e in $envs) { $members[$e.id] = @((Hub GET "/environments/$($e.id)/members").members) }
  $ca = @()
  if ($envs) { try { $ca = @((Hub GET "/environments/$($envs[0].id)/ssh-ca").public_keys) } catch { $ca = @() } }
  @{ environments = @($envs | ForEach-Object { @{ id = $_.id; name = $_.name; state = $_.state; ownerUserId = $_.ownerUserId } }); members = $members; ca = $ca }
}

# Pure: hub snapshot -> desired state for devbox-teams. The hub owner of each environment is `-Owner` (dev);
# everyone else maps to their hub linux_username (u-<8hex>); members without one (viewers) are skipped.
function ConvertTo-Desired($snap) {
  $repos = [ordered]@{}
  foreach ($e in $snap.environments) {
    $r = Get-RepoOfEnv ([pscustomobject]$e); if (-not $r) { continue }
    $list = @([ordered]@{ linux = $Owner; role = 'owner' })
    foreach ($m in @($snap.members[$e.id])) {
      $role = "$($m.role)"; $lu = "$($m.linux_username)"
      if ("$($m.user_id)" -eq "$($e.ownerUserId)") { continue }   # the machine owner = $Owner (dev)
      if ($lu -notmatch '^u-[0-9a-f]{8}$') { continue }
      $list += [ordered]@{ linux = $lu; role = $role }
    }
    $repos[$r] = [ordered]@{ members = @($list) }
  }
  [ordered]@{ version = 1; owner = $Owner; ca_keys = @($snap.ca | Where-Object { $_ }); repos = $repos }
}

$snap = Get-Snapshot
$desired = ConvertTo-Desired $snap
$json = $desired | ConvertTo-Json -Depth 6
if ($DesiredOnly) { $json; exit 0 }
# the devbox suspends itself after 30 min idle: skip (exit 0) instead of failing the task every 15 min;
# the Unix state on the devbox stays enforced and the next run while it is RUNNING converges it.
# DEVBOX_TEAMS_STATUS overrides the probe (tests); an unknown status (gcloud error) falls through to the ssh.
$st = if ($env:DEVBOX_TEAMS_STATUS) { $env:DEVBOX_TEAMS_STATUS } else {
  $o0 = @(& gcloud compute instances describe $DevboxName --zone europe-west4-b --project codai-training --format='value(status)' 2>$null)
  if ($LASTEXITCODE -eq 0) { "$($o0 | Select-Object -First 1)".Trim() }
}
if ($st -and $st -ne 'RUNNING') {
  New-Item -ItemType Directory -Force (Split-Path $Log) | Out-Null
  Add-Content $Log ('{0:o} skip repos={1} status={2}' -f (Get-Date), $desired.repos.Count, $st)
  "SKIP: $DevboxName is $st (devbox state stays enforced; applied on the next run while it is up)"
  exit 0
}
$verb = if ($Plan) { 'plan' } else { 'apply' }
# desired state over stdin of an IAP/Tailscale ssh as the provisioning user (sudo); never a secret in it
$c = @('--zone', 'europe-west4-b', '--project', 'codai-training', '--tunnel-through-iap', '--quiet', '--strict-host-key-checking=no')
$tmp = Join-Path ([IO.Path]::GetTempPath()) ('teams-' + [guid]::NewGuid().ToString('n') + '.json')
[IO.File]::WriteAllText($tmp, ($json -replace "`r`n", "`n"), [Text.UTF8Encoding]::new($false))
try {
  $o1 = & gcloud compute scp $tmp "${DevboxName}:/tmp/agentq-teams.json" @c 2>&1
  if ($LASTEXITCODE) { throw "scp to $DevboxName failed: $($o1 | Select-Object -Last 2)" }
  $out = @(& gcloud compute ssh $DevboxName @c --command "sudo /usr/local/sbin/devbox-teams $verb --file /tmp/agentq-teams.json; rc=`$?; rm -f /tmp/agentq-teams.json; echo TEAMS_RC=`$rc" 2>&1 | ForEach-Object { "$_" })
} finally { Remove-Item -LiteralPath $tmp -Force -ErrorAction SilentlyContinue }
$out | Where-Object { $_ -match '^(->|   |TEAMS_|REFUSED|WARN)' }
New-Item -ItemType Directory -Force (Split-Path $Log) | Out-Null
$rc = ($out | Select-String 'TEAMS_RC=(\d+)' | Select-Object -Last 1).Matches.Groups[1].Value
Add-Content $Log ('{0:o} {1} repos={2} rc={3} actions={4}' -f (Get-Date), $verb, $desired.repos.Count, $rc, @($out | Where-Object { $_ -like '->*' }).Count)
if ($rc -ne '0') { exit 1 }
